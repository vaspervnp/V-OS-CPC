#!/usr/bin/env python3
"""Convert font8x8_basic.h (public domain, Daniel Hepper) to RASM source.

The C table stores the leftmost pixel in bit 0; the CPC routines expect it
in bit 7, so every row is bit-reversed. Only codes 32..127 are emitted.

Usage: tools/mkfont.py tools/fonts/font8x8_basic.h src/gfx/font_ascii.asm
"""
import re
import sys


def main(src, dst):
    text = open(src, encoding="ascii").read()
    rows = re.findall(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,?\s*){8})\}", text)
    if len(rows) != 128:
        sys.exit(f"expected 128 glyphs, found {len(rows)}")
    out = [
        "; =====================================================================",
        "; font_ascii.asm - 8x8 font, codes 32..127, bit 7 = leftmost pixel",
        "; Generated by tools/mkfont.py from tools/fonts/font8x8_basic.h",
        "; (Daniel Hepper, after the IBM VGA fonts; public domain). Do not edit.",
        "; =====================================================================",
        "",
        "font_ascii:",
    ]
    for code in range(32, 128):
        vals = [int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]{2}", rows[code])]
        rev = [int(f"{v:08b}"[::-1], 2) for v in vals]
        ch = chr(code) if 32 < code < 127 else ("space" if code == 32 else "del")
        out.append("        db " + ",".join(f"#{v:02X}" for v in rev) + f"   ; {code:3d} {ch}")
    open(dst, "w", encoding="ascii").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
