#!/usr/bin/env python3
"""One-off generator for lang/el/font.txt (codes 128..255, ISO 8859-7).

Glyphs come from font8x8_greek.h and font8x8_ext_latin.h (Daniel Hepper,
public domain). Letters the source lacks (capitals with tonos, ϊ ϋ ό ύ ώ,
΄ ΅ ·, quotes, horizontal bar) are composed from a base glyph plus an
accent. ά έ ή ί are composed too, so every lower-case letter carries the
same steep tonos. The output is meant to be edited by hand afterwards;
mklng.py reads lang/el/font.txt, not this script.

Usage: tools/fonts/make_greek_font.py > lang/el/font.txt
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))


def load(name, first):
    """Return {codepoint: [8 row strings]} from a font8x8 header."""
    text = open(os.path.join(HERE, name), encoding="ascii").read()
    rows = re.findall(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,?\s*){8})\}", text)
    glyphs = {}
    for i, row in enumerate(rows):
        vals = [int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]{2}", row)]
        # font8x8: bit 0 = leftmost pixel
        glyphs[first + i] = ["".join("#" if v >> b & 1 else "." for b in range(8)) for v in vals]
    return glyphs


GREEK = load("font8x8_greek.h", 0x0390)
LATIN = load("font8x8_ext_latin.h", 0x00A0)
ASCII = load("font8x8_basic.h", 0x0000)
BLANK = ["." * 8] * 8


def overlay(base, marks):
    """OR the '#' pixels of marks onto base."""
    return ["".join("#" if a == "#" or b == "#" else "." for a, b in zip(r1, r2))
            for r1, r2 in zip(base, marks)]


def shift_right(glyph, n=1):
    return [("." * n + r)[:8] for r in glyph]


def mark(rows):
    return rows + ["." * 8] * (8 - len(rows))


TONOS_CAP = mark(["##......", "#......."])          # left of a capital
TONOS_LOW = mark(["....##..", "...##..."])          # above a lowercase
DIAER_LOW = mark(["........", ".##..##."])          # above a lowercase


def capital_tonos(cp):
    return overlay(shift_right(GREEK[cp], 1), TONOS_CAP)


def compose():
    g = {}
    g[0xA0] = LATIN[0xA0]
    g[0xA1] = ASCII[ord("`")]
    g[0xA2] = ASCII[ord("'")]
    g[0xA3] = LATIN[0xA3]
    for cp in (0xA6, 0xA7, 0xA8, 0xA9, 0xAB, 0xAC, 0xAD, 0xB0, 0xB1, 0xB2, 0xB3, 0xBB, 0xBD):
        g[cp] = LATIN[cp]
    g[0xAF] = mark(["........", "........", "........", "########"])
    g[0xB4] = mark(["....##..", "...##..."])                       # ΄
    g[0xB5] = mark(["#..##..#", "..##...."])                       # ΅
    g[0xB7] = mark(["........", "........", "...##...", "...##..."])  # ·
    g[0xB6] = capital_tonos(0x0391)                                 # Ά
    g[0xB8] = capital_tonos(0x0395)                                 # Έ
    g[0xB9] = capital_tonos(0x0397)                                 # Ή
    g[0xBA] = capital_tonos(0x0399)                                 # Ί
    g[0xBC] = capital_tonos(0x039F)                                 # Ό
    g[0xBE] = capital_tonos(0x03A5)                                 # Ύ
    g[0xBF] = capital_tonos(0x03A9)                                 # Ώ
    # C0..FE follow U+0390..U+03CE one to one, D2 is unassigned
    for code in range(0xC0, 0xFF):
        cp = code - 0xC0 + 0x0390
        if code == 0xD2:
            continue
        if cp in GREEK and cp <= 0x03C9:
            g[code] = GREEK[cp]
    g[0xFA] = overlay(GREEK[0x03B9], DIAER_LOW)                     # ϊ
    g[0xFB] = overlay(GREEK[0x03C5], DIAER_LOW)                     # ϋ
    g[0xDC] = overlay(GREEK[0x03B1], TONOS_LOW)                     # ά
    g[0xDD] = overlay(GREEK[0x03B5], TONOS_LOW)                     # έ
    g[0xDE] = overlay(GREEK[0x03B7], TONOS_LOW)                     # ή
    g[0xDF] = overlay(GREEK[0x03B9], TONOS_LOW)                     # ί
    g[0xFC] = overlay(GREEK[0x03BF], TONOS_LOW)                     # ό
    g[0xFD] = overlay(GREEK[0x03C5], TONOS_LOW)                     # ύ
    g[0xFE] = overlay(GREEK[0x03C9], TONOS_LOW)                     # ώ
    return g


def main():
    g = compose()
    print("# V-OS language pack font: codes 128..255, 8x8, '#' = ink.")
    print("# Generated by tools/fonts/make_greek_font.py, then free to edit.")
    print("# Glyphs from font8x8 (Daniel Hepper, public domain) and composed accents.")
    for code in range(128, 256):
        try:
            ch = bytes([code]).decode("iso8859_7")
            label = ch if ch.isprintable() and not ch.isspace() else ""
        except UnicodeDecodeError:
            label = ""
        print()
        print(f"{code:02X} {label}".rstrip())
        for row in g.get(code, BLANK):
            print(row)


if __name__ == "__main__":
    main()
