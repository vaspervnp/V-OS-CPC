#!/usr/bin/env python3
"""One-off generator for lang/vos/font.txt (codes 128..255 of the V-OS
character set, tools/voscs.py), the font of every language pack.

It merges the two fonts before it, as their generators make them: the
Greek one (make_greek_font.py, ISO 8859-7) for the codes the V-OS set
keeps from ISO 8859-7, and the Latin one (make_latin_font.py, ISO
8859-1) for the letters of French, Spanish, German and Italian, each
taken from its ISO 8859-1 code. The
output is meant to be edited by hand afterwards; mklng.py reads
lang/vos/font.txt, not this script.

Usage: tools/fonts/make_vos_font.py > lang/vos/font.txt
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import voscs                        # noqa: E402
from mklng import read_font         # noqa: E402


# glyphs neither font has
OWN = {
    "€": ["..####..",
          ".##..##.",
          "######..",
          ".##.....",
          "######..",
          ".##..##.",
          "..####..",
          "........"],
}


def font_of(script):
    text = subprocess.run([sys.executable, os.path.join(HERE, script)],
                          check=True, capture_output=True).stdout
    with tempfile.NamedTemporaryFile(suffix=".txt") as f:
        f.write(text)
        f.flush()
        return read_font(f.name)


def main():
    greek = font_of("make_greek_font.py")
    latin = font_of("make_latin_font.py")
    print("# V-OS font: codes 128..255 of the V-OS character set "
          "(tools/voscs.py), 8x8,")
    print("# '#' = ink. Every language pack has it (pack.txt: font).")
    print("# Generated by tools/fonts/make_vos_font.py from the Greek and "
          "Latin-1 fonts,")
    print("# then free to edit. Glyphs from font8x8 (Daniel Hepper, public "
          "domain).")
    for code in range(128, 256):
        ch = voscs.DECODE[code]
        try:
            iso7 = bytes([code]).decode("iso8859_7")
        except UnicodeDecodeError:
            iso7 = None
        if ch in OWN:
            rows = [int(r.replace("#", "1").replace(".", "0"), 2) for r in OWN[ch]]
        elif ch == iso7:
            rows = greek.get(code, [0] * 8)
        else:
            rows = latin[ch.encode("latin-1")[0]]
        print()
        print("%02X  %s" % (code, ch if ch.isprintable() and ch != "\xa0" else ""))
        for r in rows:
            print(format(r, "08b").replace("1", "#").replace("0", "."))


if __name__ == "__main__":
    main()
