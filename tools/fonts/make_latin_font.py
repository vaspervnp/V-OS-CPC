#!/usr/bin/env python3
"""One-off generator for lang/latin1/font.txt (codes 128..255, ISO 8859-1),
the font of the French, Spanish, German and Italian packs.

Glyphs A0..FF come from font8x8_ext_latin.h (Daniel Hepper, public
domain), which follows U+00A0..U+00FF one to one; 80..9F are control
codes in ISO 8859-1 and stay blank. Its capitals with a mark are five
rows high, under a blank row and the mark: smaller than the others, but
the mark stays clear of the letter (a seven-row capital leaves it no
room in 8 x 8). The output is meant to be edited by hand afterwards;
mklng.py reads lang/latin1/font.txt, not this script.

Usage: tools/fonts/make_latin_font.py > lang/latin1/font.txt
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))


def load(name, first):
    """Return {codepoint: [8 row strings]} from a font8x8 header."""
    text = open(os.path.join(HERE, name), encoding="ascii").read()
    rows = re.findall(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,?\s*){8})\}", text)
    glyphs = {}
    for i, row in enumerate(rows):
        vals = [int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]{2}", row)]
        # font8x8: bit 0 = leftmost pixel
        glyphs[first + i] = ["".join("#" if v >> b & 1 else "." for b in range(8)) for v in vals]
    return glyphs


LATIN = load("font8x8_ext_latin.h", 0x00A0)
BLANK = ["." * 8] * 8


def main():
    print("# V-OS language pack font: codes 128..255, 8x8, '#' = ink. ISO 8859-1,")
    print("# shared by the French, Spanish, German and Italian packs (pack.txt: font).")
    print("# Generated by tools/fonts/make_latin_font.py, then free to edit.")
    print("# Glyphs from font8x8 (Daniel Hepper, public domain).")
    for code in range(128, 256):
        ch = bytes([code]).decode("iso8859_1")
        label = ch if ch.isprintable() and not ch.isspace() else ""
        print()
        print(f"{code:02X} {label}".rstrip())
        for row in LATIN.get(code, BLANK) if code >= 0xA0 else BLANK:
            print(row)


if __name__ == "__main__":
    main()
