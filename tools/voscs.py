"""The V-OS character set: one 8-bit code for every language of V-OS.

Codes 0..127 are ASCII. 128..255 are ISO 8859-7 (Greek) as it is, so a
Greek file needs no conversion, with the letters of French, Spanish,
German and Italian in the codes ISO 8859-7 leaves free or that V-OS does
not use (#80-#9F, the rare signs of #A0-#BD, #D2, #FF):

  #80-#95  A grave .. U diaeresis   (capitals, as in LATIN below)
  #96-#9F, #A0 #A5 #A6 #A9 #AA #AC #AD #AE #AF #B1 #B2 #B3 #BD
           their small letters and sharp s
  #D2 #FF  inverted ! and ?

Written in V-OS, two more signs take a code they look like: the acute
accent is the Greek tonos (#B4) and the micro sign is mu (#EC). Not in
it: y diaeresis, OE ligature.

python3 tools/voscs.py fold | utf8 writes the tables of src/db/fold.inc
and src/kernel/utf8.inc.

import voscs registers the codec "vos": text.encode("vos"),
data.decode("vos"). tools/mklng.py builds the packs with it, and
tools/mktexts.py, tools/mkvbs.py and blocks/vbc.py the program texts.
"""

import codecs
import sys
import unicodedata

LATIN_CAPS = "ÀÁÂÄÇÈÉÊËÌÍÎÏÑÒÓÔÖÙÚÛÜ"
LATIN_SMALL = "àáâäçèéêëìíîïñòóôöùúûüß"
SMALL_CODES = list(range(0x96, 0xA0)) + [0xA0, 0xA5, 0xA6, 0xA9, 0xAA, 0xAC,
                                         0xAD, 0xAE, 0xAF, 0xB1, 0xB2, 0xB3,
                                         0xBD]
FREED = [0xA0, 0xA5, 0xA6, 0xA9, 0xAA, 0xAC, 0xAD, 0xAE, 0xAF, 0xB1, 0xB2,
         0xB3, 0xBD]


def _table():
    t = {}
    for code in range(128):
        t[code] = chr(code)
    for code in range(0xA0, 0x100):
        if code in FREED:
            continue
        try:
            t[code] = bytes([code]).decode("iso8859_7")
        except UnicodeDecodeError:
            pass
    for i, ch in enumerate(LATIN_CAPS):
        t[0x80 + i] = ch
    for code, ch in zip(SMALL_CODES, LATIN_SMALL):
        t[code] = ch
    t[0xD2] = "¡"
    t[0xFF] = "¿"
    return t


DECODE = _table()
assert len(DECODE) == 256, sorted(set(range(256)) - set(DECODE))
ENCODE = {ch: code for code, ch in DECODE.items()}
ENCODE["´"] = 0xB4                  # acute accent: tonos
ENCODE["µ"] = 0xEC                  # micro sign: mu
ENCODE["\u00a0"] = 0x20              # no-break space: a space
ENCODE["\u201c"] = ENCODE["\u201d"] = 0x22   # quotation marks: "
ENCODE["\u2013"] = ENCODE["\u2014"] = 0x2D   # dashes: -
ENCODE["’"] = ENCODE.get("’", 0xA2)


def encode(text, errors="strict"):
    out = bytearray()
    for i, ch in enumerate(text):
        code = ENCODE.get(ch)
        if code is None:
            if errors == "strict":
                raise UnicodeEncodeError("vos", text, i, i + 1,
                                         "not in the V-OS character set")
            if errors == "replace":
                code = ord("?")
            else:
                continue
        out.append(code)
    return bytes(out), len(text)


def decode(data, errors="strict"):
    return "".join(DECODE[b] for b in bytes(data)), len(data)


def _search(name):
    if name in ("vos", "v_os", "v-os"):
        return codecs.CodecInfo(encode, decode, name="vos")
    return None


codecs.register(_search)


def fold(code):
    """A code -> its letter without case or accent (É -> E, ά -> Α, ς -> Σ,
    ß -> S), for sorting and finding; other codes stay as they are."""
    ch = DECODE[code]
    base = "".join(c for c in unicodedata.normalize("NFD", ch)
                   if not unicodedata.combining(c)).upper()[:1]
    if not base or not ch.isalpha():
        return code
    return ENCODE.get(base, code)


def fold_asm():
    """src/db/fold.inc: fold() of the codes 128..255, for DB.SYS."""
    out = ["; Generated by tools/voscs.py fold: do not edit. The V-OS codes",
           "; 128..255 without case or accent (DB_ALPHA keys, db/db.asm).",
           "fold_tab:"]
    for hi in range(128, 256, 16):
        out.append("        db " + ", ".join("#%02X" % fold(c) for c in range(hi, hi + 16)))
    return "\n".join(out) + "\n"


def utf8_asm():
    """src/kernel/utf8.inc: the Unicode of the codes 128..255 and the signs
    written as another code, for src/kernel/utf8.asm."""
    out = ["; Generated by tools/voscs.py utf8: do not edit. The Unicode of the",
           "; V-OS codes 128..255 (kernel/utf8.asm), then other signs: dw Unicode,",
           "; db code, ending with dw 0.",
           "u8_tab:"]
    for hi in range(128, 256, 8):
        out.append("        dw " + ", ".join("#%04X" % ord(DECODE[c]) for c in range(hi, hi + 8)))
    out.append("u8_more:")
    for ch, code in sorted(ENCODE.items()):
        if DECODE[code] != ch and ord(ch) >= 128:
            out.append("        dw #%04X : db #%02X   ; %s" % (ord(ch), code, unicodedata.name(ch).lower()))
    out.append("        dw 0")
    return "\n".join(out) + "\n"


def char_table():
    """Code -> character, for the docs: lines of 16."""
    rows = []
    for hi in range(8, 16):
        rows.append("%X_ " % hi + " ".join(
            DECODE[hi * 16 + lo] if DECODE[hi * 16 + lo].isprintable()
            and DECODE[hi * 16 + lo] != "\xa0" else "." for lo in range(16)))
    return "\n".join(rows)


if __name__ == "__main__":
    if sys.argv[1:] == ["fold"]:
        sys.stdout.write(fold_asm())
    elif sys.argv[1:] == ["utf8"]:
        sys.stdout.write(utf8_asm())
    else:
        print(char_table())
